from typing import Any

from pydantic import BaseModel, Field


class CriticResponse(BaseModel):
    confidence: int = Field(
        ..., description="How confident the critic is that the answer is reliable."
    )
    is_correct: bool = Field(
        ..., description="Whether the answer is supported by retrieved information."
    )
    reasoning: str = Field(..., description="Why the critic gave that confidence.")
    feedback: str = Field(..., description="Feedback on the RAG response.")


class RetrievedDocument(BaseModel):
    content: str = Field(..., description="Retrieved document content")
    meta_data: dict[str, Any] = Field(
        default_factory=dict, description="Document metadata"
    )


class RagRespone(BaseModel):
    query: str = Field(..., description="Original query from the user")
    answer: str = Field(..., description="Answer generated by the RAG model")
    sources: list[str] = Field(
        default_factory=list, description="Documents retrieved from the vector store."
    )
    critic_response: CriticResponse | None = Field(
        default=None,
        description="Critic evaluation of the generated answer, when available.",
    )


class QueryContextDecision(BaseModel):
    depends_on_history: bool = Field(
        ...,
        description="Whether the latest question requires earlier conversation turns.",
    )
    standalone_query: str = Field(
        ...,
        description=(
            "A standalone rewrite if history is needed; otherwise return "
            "the latest question unchanged."
        ),
    )
