import os

from agent_framework_ollama import OllamaChatClient

from src.core.config import config
from src.core.logger import logger

INSTRUCTIONS = """
You are a RAG response critic.

Your task is to evaluate the response generated by the RAG agent using the original user query, the generated answer, and the retrieved information.

Evaluate whether the RAG answer is reliable and properly supported by the retrieved information.

You must evaluate:

* Whether the answer correctly answers the user's query.
* Whether the answer is supported by the retrieved documents.
* Whether the answer contains unsupported or hallucinated information.
* Whether important information from the retrieved documents was missed.
* Whether the answer is relevant to the user's question.

Assign a confidence as an integer from 0 to 100.

Use the following guideline:

* 90 to  100: Highly reliable and strongly supported by the retrieved information.
* 75 to 89: Reliable with minor issues.
* 50 to 74: Partially reliable; some information may be missing or questionable.
* 25 to 49: Low reliability; significant issues exist.
* 0 to 24: Incorrect, irrelevant, or largely unsupported.

The `is_correct` field must be true only when the answer is sufficiently supported by the retrieved information and correctly addresses the user's query.

The `reasoning` field must explain why you assigned the confidence score and why the answer is or is not correct.

The `feedback` field must provide specific feedback that can be used by the RAG agent to improve its response when the confidence is low.

Do not generate a new answer to the user's question.

Do not modify or invent information from the retrieved documents.

Your role is only to evaluate the RAG response and provide a confidence score, correctness judgment, reasoning, and improvement feedback.

Return only the required structured response.
"""


class CriticAgent:
    def __init__(self):
        self.model = config["Application"]["rag"]["llm_model"]
        try:
            self.client = OllamaChatClient(
                model=self.model,
                host=os.getenv("OLLAMA_HOST"),
            )
            logger.info(
                "OllamaChatClient initialized with model_id: %s",
                self.model,
            )
        except Exception as exc:
            logger.exception("Failed to initialize OllamaChatClient.")
            raise RuntimeError(
                f"Could not initialize Ollama model '{self.model}'."
            ) from exc
        try:
            self.critic_agent = self.client.as_agent(
                instructions=INSTRUCTIONS,
            )
            logger.info("RAGAgent initialized successfully.")
        except Exception as exc:
            logger.exception("Failed to create the chat agent.")
            raise RuntimeError("Could not create the Ollama agent.") from exc

    @property
    def agent(self):
        return self.critic_agent
