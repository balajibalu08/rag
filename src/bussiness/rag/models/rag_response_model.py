from typing import Any

from pydantic import BaseModel, Field

from src.bussiness.rag.models.critic_response_model import CriticResponse


class RetrievedDocument(BaseModel):
    content: str = Field(..., description="Retrived Document content")
    meta_data: dict[str, str | int | None | Any] = Field(
        default_factory=dict, description="Metadata of the document"
    )


class RagRespone(BaseModel):
    query: str = Field(..., description="original querry from user")
    answer: str = Field(..., description="Answer generated by rag model")
    sources: list[str] = Field(
        default_factory=list, description="Documents retrived from the vector store."
    )
    critic_response: CriticResponse | None = Field(
        default=None,
        description="Critic evaluation of the generated answer, when available.",
    )
